"""Core Data Models and Pydantic Schemas for Local Command Bot."""

from enum import Enum
from datetime import datetime, timezone
from typing import Any, Optional
from pydantic import BaseModel, Field, ConfigDict


def utc_now() -> datetime:
    """Return current UTC datetime."""
    return datetime.now(timezone.utc)


class TaskStatus(str, Enum):
    """Lifecycle statuses for a task."""
    PENDING = "PENDING"
    READY = "READY"
    RUNNING = "RUNNING"
    VALIDATING = "VALIDATING"
    SUCCEEDED = "SUCCEEDED"
    FAILED = "FAILED"
    RETRYING = "RETRYING"
    CANCELLED = "CANCELLED"


class JobStatus(str, Enum):
    """Lifecycle statuses for a high-level job."""
    PENDING = "PENDING"
    PLANNING = "PLANNING"
    RUNNING = "RUNNING"
    PAUSED = "PAUSED"
    SUCCEEDED = "SUCCEEDED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"


class TaskRole(str, Enum):
    """Operational roles assigned to AI tasks."""
    PLANNER = "PLANNER"
    RESEARCHER = "RESEARCHER"
    WRITER = "WRITER"
    REVIEWER = "REVIEWER"
    AUDITOR = "AUDITOR"
    BUILDER = "BUILDER"


class OutputFormat(str, Enum):
    """Output document formats supported."""
    DOCX = "DOCX"
    PDF = "PDF"
    MD = "MD"


class TokenUsage(BaseModel):
    """Token consumption and cost tracking."""
    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0
    estimated_cost_usd: float = 0.0


class ReviewCritique(BaseModel):
    """Individual critique item produced by Reviewer."""
    category: str = Field(..., description="completeness, logic, consistency, redundancy, contradiction, citations, unverified_claims, compliance")
    severity: str = Field(default="WARNING", description="INFO, WARNING, CRITICAL")
    section_id: Optional[str] = Field(default=None, description="Section ID requiring revision")
    description: str = Field(..., description="Detailed description of the issue")
    suggested_fix: str = Field(..., description="Actionable instruction to resolve the issue")


class ReviewResult(BaseModel):
    """Comprehensive evaluation from Reviewer."""
    is_approved: bool = Field(..., description="True if document section meets acceptance criteria")
    score: float = Field(default=10.0, description="Quality score from 0.0 to 10.0")
    critiques: list[ReviewCritique] = Field(default_factory=list)
    summary: str = Field(default="", description="High level review summary")


class TaskPlanItem(BaseModel):
    """Blueprint of a task within JobPlan."""
    task_id: str
    title: str
    role: TaskRole = TaskRole.WRITER
    provider: str = "openai"
    model: str = "gpt-4o-mini"
    instructions: str
    dependencies: list[str] = Field(default_factory=list)
    result_format: str = "markdown"
    acceptance_criteria: list[str] = Field(default_factory=list)
    section_id: Optional[str] = None
    section_order: int = 1


class JobPlan(BaseModel):
    """Validated blueprint generated by Planner from user prompt."""
    objective: str = Field(..., description="Main objective of the requested document")
    doc_type: str = Field(default="SOP", description="SOP, Technical Spec, Report, Guide, etc.")
    language: str = Field(default="Vietnamese", description="Target document language")
    target_audience: str = Field(default="QA/QC Staff and Operations", description="Intended readership")
    scope: str = Field(default="", description="Scope and boundaries of document")
    output_structure: list[str] = Field(default_factory=list, description="Ordered list of chapter/section titles")
    tasks: list[TaskPlanItem] = Field(..., description="Granular task decomposition")
    references_to_consult: list[str] = Field(default_factory=list, description="Official legal and regulatory references")
    time_limit_seconds: float = Field(default=600.0, description="Max execution duration in seconds")
    budget_limit_usd: float = Field(default=5.0, description="Max allowed spending in USD")
    assumptions_requiring_confirmation: list[str] = Field(default_factory=list)


class Task(BaseModel):
    """Executable task instance managed by Scheduler and SQLite."""
    task_id: str
    job_id: str
    role: TaskRole
    provider: str
    model: str
    input: dict[str, Any] = Field(default_factory=dict)
    dependencies: list[str] = Field(default_factory=list)
    status: TaskStatus = TaskStatus.PENDING
    attempt_count: int = 0
    max_attempts: int = 3
    output_path: Optional[str] = None
    output_content: Optional[str] = None
    error_message: Optional[str] = None
    usage: TokenUsage = Field(default_factory=TokenUsage)
    review_result: Optional[ReviewResult] = None
    created_at: datetime = Field(default_factory=utc_now)
    updated_at: datetime = Field(default_factory=utc_now)

    model_config = ConfigDict(arbitrary_types_allowed=True)


class Job(BaseModel):
    """Master job instance encapsulating execution lifecycle."""
    job_id: str
    prompt: str
    status: JobStatus = JobStatus.PENDING
    plan: Optional[JobPlan] = None
    output_formats: list[OutputFormat] = Field(default_factory=lambda: [OutputFormat.DOCX, OutputFormat.MD])
    output_dir: str
    budget_limit_usd: float = 5.0
    total_cost_usd: float = 0.0
    total_tokens: int = 0
    max_concurrency: int = 3
    max_retries: int = 3
    timeout_seconds: float = 90.0
    dry_run: bool = False
    created_at: datetime = Field(default_factory=utc_now)
    updated_at: datetime = Field(default_factory=utc_now)
    completed_at: Optional[datetime] = None
    generated_files: list[str] = Field(default_factory=list)
    error_message: Optional[str] = None

    model_config = ConfigDict(arbitrary_types_allowed=True)


class SourceReference(BaseModel):
    """Tracked legal/technical source citation."""
    reference_id: str
    job_id: str
    title: str
    issuing_body: str = "Bộ Y Tế / Cục Quản lý Dược"
    doc_number: Optional[str] = None
    doc_type: str = "Thông tư / Quy chuẩn / Dược điển"
    issue_date: Optional[str] = None
    url: Optional[str] = None
    status: str = "Chưa xác minh — cần kiểm tra thủ công"
    clause_used: Optional[str] = None
    is_mandatory: bool = True
    verified_at: Optional[datetime] = None
